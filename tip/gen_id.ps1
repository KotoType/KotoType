$ErrorActionPreference = 'Stop'
$bytes = [System.IO.File]::ReadAllBytes((Join-Path $PSScriptRoot 'kototype_tip.cpp'))
$sha = [System.Security.Cryptography.SHA256]::Create()
$h = $sha.ComputeHash($bytes)

function Format-GuidParts([byte[]]$b) {
    # RFC 4122 version 5, variant 1.
    $b[6] = ($b[6] -band 0x0f) -bor 0x50
    $b[8] = ($b[8] -band 0x3f) -bor 0x80
    $d1 = ([uint32]$b[0] -shl 24) -bor ([uint32]$b[1] -shl 16) -bor ([uint32]$b[2] -shl 8) -bor [uint32]$b[3]
    $d2 = ([uint16]$b[4] -shl 8) -bor [uint16]$b[5]
    $d3 = ([uint16]$b[6] -shl 8) -bor [uint16]$b[7]
    $d4 = ($b[8..15] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', '
    $init = '{{0x{0:x8}, 0x{1:x4}, 0x{2:x4}, {{{3}}}}}' -f $d1, $d2, $d3, $d4
    $d4a = '{0:X2}{1:X2}' -f $b[8], $b[9]
    $d4b = ($b[10..15] | ForEach-Object { '{0:X2}' -f $_ }) -join ''
    $str = '{{{0:X8}-{1:X4}-{2:X4}-{3}-{4}}}' -f $d1, $d2, $d3, $d4a, $d4b
    return @{ Init = $init; Str = $str; Short = ('{0:x8}' -f $d1) }
}

$clsid = Format-GuidParts $h[0..15]
$prof  = Format-GuidParts $h[16..31]
$wcls  = "KotoTypeTipWindow.$($clsid.Short)"

$header = @"
// Generated by tip/gen_id.ps1 from kototype_tip.cpp; do not edit.
#pragma once
#define KT_CLSID_INIT $($clsid.Init)
#define KT_PROFILE_INIT $($prof.Init)
#define KT_CLSID_STR L"$($clsid.Str)"
#define KT_WINDOW_CLASS L"$wcls"
"@
[System.IO.File]::WriteAllText((Join-Path $PSScriptRoot 'tip_id.h'), $header, [System.Text.UTF8Encoding]::new($false))

$go = @"
package tip

// Generated by tip/gen_id.ps1 from kototype_tip.cpp; do not edit.
const (
	// WindowClass is the message-only window class used by this build's DLL.
	WindowClass = "$wcls"

	currentCLSID = "$($clsid.Str)"
)
"@
$goPath = Join-Path $PSScriptRoot '..\internal\tip\id_generated.go'
[System.IO.File]::WriteAllText($goPath, $go, [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated TIP ID: CLSID=$($clsid.Str) Class=$wcls"
